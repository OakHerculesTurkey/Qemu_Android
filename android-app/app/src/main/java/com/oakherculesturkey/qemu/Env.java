package com.oakherculesturkey.qemu;

import android.content.Context;
import android.content.pm.PackageInfo;
import android.content.res.AssetManager;
import android.net.ConnectivityManager;
import android.net.LinkProperties;
import android.net.Network;

import java.io.File;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.net.Inet4Address;
import java.net.InetAddress;

/** App-wide locations and the one-time extraction of QEMU's data files. */
final class Env {
    private Env() {}

    private static final String ASSET_ROOT = "qemu";

    /** Where QEMU binaries live (lib*.so extracted by the package manager). */
    static File binDir(Context c) {
        return new File(c.getApplicationInfo().nativeLibraryDir);
    }

    /** QEMU firmware/keymaps directory, passed to QEMU with -L. */
    static File dataDir(Context c) {
        return new File(c.getFilesDir(), "qemu-share");
    }

    static File qemuImg(Context c) {
        return new File(binDir(c), "libqemu-img.so");
    }

    private static String stampValue(Context c) {
        try {
            PackageInfo pi = c.getPackageManager().getPackageInfo(c.getPackageName(), 0);
            return pi.lastUpdateTime + ":" + pi.versionName;
        } catch (Exception e) {
            return "unknown";
        }
    }

    static boolean dataReady(Context c) {
        File stamp = new File(dataDir(c), ".stamp");
        return stamp.exists() && stampValue(c).equals(Files.readText(stamp, 200).trim());
    }

    /** Copies assets/qemu to filesDir/qemu-share once per installed APK version. */
    static synchronized void ensureData(Context c) throws IOException {
        if (dataReady(c)) return;
        File dir = dataDir(c);
        Files.deleteRecursively(dir);
        if (!dir.mkdirs() && !dir.isDirectory()) throw new IOException("mkdir " + dir);
        copyAssetDir(c.getAssets(), ASSET_ROOT, dir);
        Files.writeText(new File(dir, ".stamp"), stampValue(c));
    }

    private static void copyAssetDir(AssetManager am, String path, File dst) throws IOException {
        String[] names = am.list(path);
        if (names == null) return;
        for (String n : names) {
            String child = path + "/" + n;
            String[] sub = am.list(child);
            File out = new File(dst, n);
            if (sub != null && sub.length > 0) {
                out.mkdirs();
                copyAssetDir(am, child, out);
            } else {
                File parent = out.getParentFile();
                if (parent != null) parent.mkdirs();
                try (InputStream in = am.open(child); OutputStream os = new FileOutputStream(out)) {
                    Files.copy(in, os, null);
                }
            }
        }
    }

    /**
     * Android has no /etc/resolv.conf. Writes the active network's DNS
     * servers (falling back to public resolvers) for libslirp, which reads
     * the file named by SLIRP_RESOLV_CONF (see patches/libslirp).
     */
    static File writeResolvConf(Context c) {
        StringBuilder sb = new StringBuilder("# generated by Qemu Android\n");
        int n4 = 0;
        try {
            ConnectivityManager cm = c.getSystemService(ConnectivityManager.class);
            Network net = cm.getActiveNetwork();
            LinkProperties lp = net != null ? cm.getLinkProperties(net) : null;
            if (lp != null) {
                // IPv4 first: the guest's default slirp network is IPv4
                for (InetAddress a : lp.getDnsServers()) {
                    if (a instanceof Inet4Address) {
                        sb.append("nameserver ").append(a.getHostAddress()).append('\n');
                        n4++;
                    }
                }
                for (InetAddress a : lp.getDnsServers()) {
                    if (!(a instanceof Inet4Address)) {
                        String h = a.getHostAddress();
                        int pct = h.indexOf('%');
                        if (pct > 0) h = h.substring(0, pct);
                        sb.append("nameserver ").append(h).append('\n');
                    }
                }
            }
        } catch (Exception ignored) {
            // no permission / no network: use the fallbacks below
        }
        // IPv6-only mobile networks: slirp's IPv4 DNS forwarding still needs a server
        if (n4 == 0) sb.append("nameserver 1.1.1.1\nnameserver 8.8.8.8\n");
        File f = new File(c.getFilesDir(), "resolv.conf");
        try {
            Files.writeText(f, sb.toString());
        } catch (IOException ignored) {
        }
        return f;
    }
}
